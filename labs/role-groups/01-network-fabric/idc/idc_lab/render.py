"""Render FRR and EOS configurations from the IDC topology."""
import argparse

from .model import DATA, HOSTS, L3_VNI, LAB, LEAVES, ROUTERS, STATE, VLANS, VRF
from .model import address, fabric_links, leaf_vlans, local_prefix, peers


def prefix_lists(node):
    entries = [f"ip prefix-list FABRIC-LOOPBACKS seq {i * 10} permit {router['loopback']}/32"
               for i, router in enumerate(ROUTERS.values(), 1)]
    entries.append(f"ip prefix-list SELF-LOOPBACK seq 10 permit {ROUTERS[node]['loopback']}/32")
    if node in LEAVES:
        entries.append(f"ip prefix-list TENANT-LOCAL seq 10 permit {local_prefix(node)}")
    return entries


def frr(node):
    vtep, asn = (ROUTERS[node][key] for key in ("loopback", "asn"))
    leaf = node in LEAVES
    under, over = (peers(node, family) for family in ("ipv4", "evpn"))
    outbound = "SELF-LOOPBACK" if leaf else "FABRIC-LOOPBACKS"
    rt = DATA["rt_asn"]
    lines = [
        "! Generated by tools/idc.py render",
        "frr defaults traditional", f"hostname {node}", "service integrated-vtysh-config",
        "log timestamp precision 3", f"log file {STATE / node / 'frr.log'} informational",
        "!", *prefix_lists(node), "!", f"router bgp {asn}", f" bgp router-id {vtep}",
        " no bgp default ipv4-unicast", " bgp ebgp-requires-policy",
        " bgp log-neighbor-changes", " bgp bestpath as-path multipath-relax",
    ]
    for ip, peer_as in [*under, *over]:
        lines += [f" neighbor {ip} remote-as {peer_as}", f" neighbor {ip} timers 2 6",
                  f" neighbor {ip} timers connect 2"]
    for ip, _ in over:
        lines += [f" neighbor {ip} update-source {vtep}", f" neighbor {ip} ebgp-multihop 5"]
    lines += [" !", " address-family ipv4 unicast", f"  network {vtep}/32", "  maximum-paths 2"]
    for ip, _ in under:
        lines += [f"  neighbor {ip} activate", f"  neighbor {ip} prefix-list FABRIC-LOOPBACKS in",
                  f"  neighbor {ip} prefix-list {outbound} out",
                  f"  neighbor {ip} soft-reconfiguration inbound"]
    lines += [" exit-address-family", " !", " address-family l2vpn evpn"]
    for ip, _ in over:
        lines += [f"  neighbor {ip} activate", f"  neighbor {ip} route-map EVPN-LAB in",
                  f"  neighbor {ip} route-map EVPN-LAB out"]
        if not leaf:
            lines.append(f"  neighbor {ip} attribute-unchanged next-hop")
    if leaf:
        lines.append("  advertise-all-vni")
        for vlan in leaf_vlans(node):
            vni = VLANS[vlan]["vni"]
            lines += [f"  vni {vni}", f"   rd {vtep}:{vni}", f"   route-target import {rt}:{vni}",
                      f"   route-target export {rt}:{vni}", "  exit-vni"]
    lines += [" exit-address-family", "exit", "!", "route-map EVPN-LAB permit 10", "exit", "!"]
    if leaf:
        lines += [
            "route-map TENANT-EXPORT permit 10", " match ip address prefix-list TENANT-LOCAL", "exit",
            "!", f"vrf {VRF}", f" vni {L3_VNI}", "exit-vrf", "!",
            f"router bgp {asn} vrf {VRF}", f" bgp router-id {vtep}",
            " address-family ipv4 unicast", "  redistribute connected route-map TENANT-EXPORT",
            " exit-address-family", " address-family l2vpn evpn",
            f"  rd {vtep}:{L3_VNI}", f"  route-target import {rt}:{L3_VNI}",
            f"  route-target export {rt}:{L3_VNI}", "  advertise ipv4 unicast",
            " exit-address-family", "exit", "!",
        ]
    return "\n".join([*lines, ""])


def eos(node):
    vtep, asn = (ROUTERS[node][key] for key in ("loopback", "asn"))
    leaf = node in LEAVES
    under, over = (peers(node, family) for family in ("ipv4", "evpn"))
    outbound = "SELF-LOOPBACK" if leaf else "FABRIC-LOOPBACKS"
    rt = DATA["rt_asn"]
    lines = [
        "! Candidate for vEOS-lab 4.30.x", f"hostname {node}",
        "service routing protocols model multi-agent", "ip routing", "!",
        *prefix_lists(node), "!", "interface Loopback0", f" ip address {vtep}/32", "!",
    ]
    for port, cidr, *_ in fabric_links(node):
        lines += [f"interface Ethernet{port.removeprefix('eth')}", " no switchport",
                  f" mtu {DATA['fabric_mtu']}", f" ip address {cidr}", " no shutdown", "!"]
    if leaf:
        vlans = leaf_vlans(node)
        lines += [f"vrf instance {VRF}", f"ip routing vrf {VRF}",
                  "ip virtual-router mac-address 02:00:00:00:fe:01", "!"]
        for vlan in vlans:
            lines += [f"vlan {vlan}", "!", f"interface Vlan{vlan}", f" vrf {VRF}",
                      f" ip address virtual {VLANS[vlan]['gateway']}", " no shutdown", "!"]
        lines += ["interface Ethernet3", " switchport mode trunk",
                  f" switchport trunk allowed vlan {','.join(vlans)}", " no shutdown", "!",
                  "interface Vxlan1", " vxlan source-interface Loopback0", " vxlan udp-port 4789",
                  *(f" vxlan vlan {vlan} vni {VLANS[vlan]['vni']}" for vlan in vlans),
                  f" vxlan vrf {VRF} vni {L3_VNI}", "!",
                  "route-map TENANT-EXPORT permit 10", " match ip address prefix-list TENANT-LOCAL", "!"]
    lines += [f"router bgp {asn}", f" router-id {vtep}", " no bgp default ipv4-unicast",
              " bgp bestpath as-path multipath-relax", " maximum-paths 2 ecmp 2",
              " bgp log-neighbor-changes"]
    for ip, peer_as in [*under, *over]:
        lines += [f" neighbor {ip} remote-as {peer_as}", f" neighbor {ip} timers 2 6"]
    for ip, _ in over:
        lines += [f" neighbor {ip} update-source Loopback0", f" neighbor {ip} ebgp-multihop 5",
                  f" neighbor {ip} send-community extended"]
        if not leaf:
            lines.append(f" neighbor {ip} next-hop-unchanged")
    if leaf:
        for vlan in vlans:
            vni = VLANS[vlan]["vni"]
            lines += [f" vlan {vlan}", f"  rd {vtep}:{vni}", f"  route-target both {rt}:{vni}",
                      "  redistribute learned", " !"]
    lines += [" address-family ipv4", f"  network {vtep}/32"]
    for ip, _ in under:
        lines += [f"  neighbor {ip} activate", f"  neighbor {ip} prefix-list FABRIC-LOOPBACKS in",
                  f"  neighbor {ip} prefix-list {outbound} out"]
    lines += [" !", " address-family evpn", *(f"  neighbor {ip} activate" for ip, _ in over)]
    if leaf:
        lines += [" !", f" vrf {VRF}", f"  rd {vtep}:{L3_VNI}",
                  f"  route-target import evpn {rt}:{L3_VNI}", f"  route-target export evpn {rt}:{L3_VNI}",
                  "  redistribute connected route-map TENANT-EXPORT"]
    return "\n".join([*lines, "!", ""])


def eos_host(host):
    leaf, remote = LEAVES if host == "host1" else LEAVES[::-1]
    local_vlan = ROUTERS[leaf]["local_vlan"]
    lines = ["#!/bin/sh", "set -eu", 'nic=$1', 'ip link set dev "$nic" up']
    for tag, cidr in HOSTS[host].items():
        lines += [f'ip link add link "$nic" name idc-v{tag} type vlan id {tag}',
                  f"ip addr add {cidr} dev idc-v{tag}", f"ip link set dev idc-v{tag} up"]
    lines.append(f"ip route add {local_prefix(remote)} via {address(VLANS[local_vlan]['gateway'])}"
                 f" dev idc-v{local_vlan}")
    return "\n".join([*lines, ""])


def configs():
    for node in ROUTERS:
        yield f"configs/frr/{node}.conf", frr(node)
        yield f"configs/eos/{node}.cfg", eos(node)
    for host in HOSTS:
        yield f"configs/eos/{host}.sh", eos_host(host)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    mismatches = []
    for name, content in configs():
        path = LAB / name
        if args.check:
            if not path.is_file() or path.read_text() != content:
                mismatches.append(name)
        else:
            path.write_text(content)
    if mismatches:
        parser.exit(1, "Configuration drift: " + ", ".join(mismatches) + "\n")
    print("10 FRR, EOS and host configuration files " + ("match" if args.check else "rendered"))


if __name__ == "__main__":
    main()
